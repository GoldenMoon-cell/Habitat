"""
参数选择：照搬 / 加速 / 适度压缩

── 三个候选 ──

A. 照搬艾宾浩斯（b = 0.136，无意义音节）
   1 天 89%，7 天 76%，30 天 65%
   → 一个月后还记得六成半。那不像遗忘，像归档。

B. 完全加速（那个 AI 说的：几个小时掉 50%）
   b ≈ 2.5
   6 小时 55%，1 天 37%，3 天 20%
   → 一场长对话下来，开头说的话已经忘了。

C. 适度压缩（我倾向的）
   b = 1.2
   6 小时 78%，1 天 61%，7 天 29%，30 天 16%
   → 一周内淡出视野，一个月基本想起来。

关键问题：
  玩家**每次上线**大概间隔多久？
    · 每天上线 → 一天的衰减必须**还看得见**
    · 一周一次 → 一周的衰减必须**还没死透**
    · 一个月一次 → 那时候淡掉是合理的
"""

import math

def R(t, b, w=1.0):
    return w * math.pow(1 + t, -b)

CANDS = [
    ("A 照搬艾宾浩斯", 0.136),
    ("D 目标反推", 0.6),
    ("C 太陡", 1.2),
    ("B 太狠", 2.5),
]

POINTS = [
    ("1 小时", 1 / 24),
    ("6 小时", 6 / 24),
    ("1 天", 1),
    ("3 天", 3),
    ("7 天", 7),
    ("30 天", 30),
]

print(f"{'':<16}" + "".join(f"{c[0]:>16}" for c in CANDS))
print("─" * 64)
for label, t in POINTS:
    row = f"{label:<16}"
    for _, b in CANDS:
        row += f"{R(t, b)*100:>15.0f}%"
    print(row)

print()
print("─" * 64)
print("每种参数下，「第一次跌破阈值 0.2」是多久：")
for name, b in CANDS:
    # 解 (1+t)^(-b) = 0.2  →  t = 0.2^(-1/b) - 1
    t = math.pow(0.2, -1 / b) - 1
    unit = f"{t*24:.1f} 小时" if t < 1 else f"{t:.1f} 天"
    print(f"  {name:<16} {unit}")

print()
print("─" * 64)
print("复习的加成（b / (1 + ac * 0.6)）：")
for ac in [0, 1, 2, 3]:
    b0 = 1.2
    bb = b0 / (1 + ac * 0.6)
    t = math.pow(0.2, -1 / bb) - 1
    unit = f"{t*24:.1f} 小时" if t < 1 else f"{t:.1f} 天"
    print(f"  复习 {ac} 次  b = {bb:.3f}   坚持到 {unit}")

print()
print("─" * 64)
print("巩固（皮层，b = 0.06）：")
for label, t in [("1 天", 1), ("7 天", 7), ("30 天", 30), ("365 天", 365)]:
    print(f"  {label:<10} {R(t, 0.06)*100:.0f}%")

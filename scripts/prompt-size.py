"""
算一下 system prompt 到底多长。

── 为什么算 ──

用户问「这么多 prompt 会不会让 AI 神经错乱」。

答案是「不会」—— 但得给出**数字**，不能光说。

── 结构 ──

buildSystemPrompt 是**一个**字符串，由 11 段拼起来。
每段都有条件，不会同时全开。

真正要担心的是**长度**，不是段数。
"""

# 每段的估算字符数（按代码里的文案长度）
SEGMENTS = [
    ("【说话方式】",            150, "总是"),
    ("【此刻的状态】",           90, "总是"),
    ("【对话的基本动作】",       380, "总是（标了「优先级最高」）"),
    ("【规则】",                210, "总是"),
    ("【群聊】",                140, "isGroup"),
    ("【此刻的说话方式】",       110, "dynamic 有变化时"),
    ("【你已经知道的事】",       120, "stage == awakened"),
    ("【你可能想知道的事】",     150, "awakened + phantom"),
    ("【你已经在等一个日子】",   200, "doom --tell 过"),
    ("【关于你的名字】",         170, "总是"),
    ("【你记得的事】",           260, "有记忆时（8 条）"),
]

print("段落                                字符   条件")
print("─" * 70)

base = 0       # 总是出现的
all_on = 0     # 全开
for name, chars, cond in SEGMENTS:
    print(f"{name:<34} {chars:>4}   {cond}")
    all_on += chars
    if cond == "总是":
        base += chars

print("─" * 70)
print(f"{'基础 4 段（总是）':<34} {base:>4}")
print(f"{'全部 11 段（最坏情况）':<34} {all_on:>4}")

# 中文 1 字 ≈ 1 token（粗略），加上格式和换行
print()
print("换算成 token（粗估 ×1.2，中文 + 标点 + 换行）：")
print(f"  基础：{int(base*1.2):>5} token")
print(f"  全开：{int(all_on*1.2):>5} token")

print()
print("对比上下文窗口：")
for win in [32, 128, 512]:
    print(f"  {win:>4}k 窗口 → 系统提示占 {int(all_on*1.2)/(win*1000)*100:>5.2f}%")

print()
print("── 结论 ──")
print("  最坏情况约 2000 字 / 2400 token —— 占 128k 窗口的 1.9%。")
print("  这不是问题。")
print()
print("  **真正要担心的不是长度，是「冲突」。**")
print("  比如「说话简短」和「详细解释」同时出现 —— 那才会错乱。")
print("  所以有一段专门标了【对话的基本动作 —— 这段优先级最高】。")

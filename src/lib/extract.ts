/**
 * 从对话里提取记忆。
 *
 * ── 为什么需要这个 ──
 *
 * 记忆系统的五个零件全都造好了：
 *
 *   遗忘曲线   `forgetting.ts`  ✅
 *   巩固算法   `shouldConsolidate`  ✅
 *   持久化     `autosaveNative`  ✅
 *   记忆卡 UI  `GodRail`  ✅
 *   写入源     **只有改名事件**  ❌
 *
 * **传动轴没接上。** 所以遗忘曲线在算什么？在算那两条
 * 「主人把名字改了」什么时候淡去。
 *
 * 这个文件补的就是那一根轴。
 *
 * ── 为什么用本地规则，不调 LLM ──
 *
 * 每句话多一次 API 调用 = 慢 + 贵 + 让对话变迟钝。
 *
 * 而且**不需要模型来判断什么值得记** —— 值得记的东西有形状：
 * 他在说自己。他说喜欢什么、讨厌什么。他问了什么。
 *
 * 本地规则能筛掉 80% 的废话（「嗯」「哦」「哈哈」），
 * 漏掉的也只是少记一条，不会记错。
 *
 * ── 宁漏不错 ──
 *
 * 这条原则写在所有规则里：**拿不准就不记。**
 *
 * 错记一条「他说过要吃香菜」（其实说的是不吃）比漏记十条糟糕得多 ——
 * 因为那条会进 prompt，她会一直记着错的东西。
 */

import type { Memory } from "./memoryNotes";

/* ══════════════════════════════════════════
   词表
   ══════════════════════════════════════════ */

/** 第一人称 —— 出现这些才说明"他在说自己" */
const FIRST_PERSON = [
  "我",
  "我的",
  "咱",
  "俺",
  "自己",
  "本人",
];

/**
 * 偏好词。
 *
 * 命中 → `偏好` tag（B=0.32，掉得比情绪慢，比长期快）
 */
const PREFERENCE = [
  "喜欢", "爱吃", "爱喝", "爱看", "爱听", "爱玩",
  "讨厌", "不吃", "不喝", "不看", "不听", "受不了", "烦死",
  "习惯", "一般不", "从来不", "从不",
  "最好", "最喜欢", "最讨厌",
  "口味", "迷恋", "上瘾",
];

/**
 * 情绪词。
 *
 * 命中 → `情绪` tag（B=0.4，掉得最快 —— 情绪是当下的）
 */
const EMOTION = [
  "累", "疲惫", "困", "失眠", "睡不着",
  "开心", "高兴", "舒服", "爽", "痛快",
  "难过", "难受", "郁闷", "憋屈", "委屈", "想哭",
  "生气", "火大", "烦", "暴躁", "急",
  "害怕", "慌", "紧张", "焦虑", "不安",
  "孤独", "寂寞", "空", "没意思", "无聊",
  "后悔", "遗憾",
  /* 「心情差」「状态不好」这类 —— 主语是心情，不是具体动作 */
  "心情", "状态", "情绪",
];

/**
 * 长期词 —— 身份、住处、职业。
 *
 * 命中 → `长期` tag（B=0.22，几乎不掉）
 */
const IDENTITY = [
  "我叫", "我是", "我住", "我在", "我的名字",
  "上班", "工作", "职业", "公司", "学校", "专业",
  "今年", "岁", "生日", "老家", "家乡",
];

/**
 * 在问他，不是在说自己。
 *
 * 「你觉得我今天是不是很烦」有「我」也有「烦」——
 * 但那是**问他**，不是**自述**。
 *
 * 记下来会变成「他很烦」的错记忆。**宁漏不错。**
 */
const ASKING_HIM = [
  "你觉得", "你说", "你想", "你猜", "你以为", "你懂",
  "你是不是", "你会不会", "你能不能", "你可不可以",
  "你为啥", "你怎么", "你什么",
];

/** 纯语气 —— 整句只有这些就直接跳过 */
const PURE_FILLER = [
  "嗯", "哦", "噢", "啊", "哈", "哈哈", "哈哈哈", "呵",
  "好", "好的", "行", "可以", "收到", "明白", "懂",
  "在吗", "在么", "你好", "您好", "早", "晚安", "早安",
  "谢谢", "谢了", "多谢",
  "对", "是的", "没错", "确实",
  "嗯嗯", "哦哦", "好好",
  "。。", "...", "…",
];

/* ══════════════════════════════════════════
   判断
   ══════════════════════════════════════════ */

export interface Extracted {
  text: string;
  tag: Memory["tag"];
  weight: number;
  /** 为什么记它 —— 显示在记忆卡的 `source` 上 */
  source: string;
}

const has = (s: string, list: string[]) => list.some((w) => s.includes(w));

/**
 * 这条值不值得记。
 *
 * 返回 `null` 就是不记 —— **大多数话都不该被记。**
 */
export function extract(text: string): Extracted | null {
  const raw = String(text ?? "").trim();
  if (!raw) return null;

  /*
   * 先剥掉 @ 和多余空白。
   *
   * 「@DeepSeek 我不吃香菜」里的 @ 是操作，不是内容 ——
   * 和 `buildHistory` 里的处理一致。
   */
  const s = raw.replace(/@\S+/g, " ").replace(/\s+/g, " ").trim();
  if (!s) return null;

  /* ── ① 纯语气 ── */
  const bare = s.replace(/[，。！？、…~～\s]/g, "");
  if (PURE_FILLER.includes(bare)) return null;
  /* 「哈哈哈哈哈哈」这种也算纯语气 */
  if (/^[哈嗯哦噢啊呵嘻嘿]+$/.test(bare)) return null;

  /*
   * 匹配用的版本：去掉所有空格。
   *
   * 「我 是 阿 野」这种手滑打出来的间隔，不该让它漏掉。
   * 存进去的仍然是原句（`s`），只是判断时用紧凑版。
   */
  const compact = s.replace(/\s+/g, "");

  /* ── ② 在问他，不是在说自己 ── */
  if (has(compact, ASKING_HIM)) return null;

  /* ── ③ 必须提到自己 ── */
  if (!has(compact, FIRST_PERSON)) return null;

  /* ── ④ 分 tag ── */
  let tag: Memory["tag"] = "短期";
  let source = "他自己说的";

  if (has(compact, IDENTITY)) {
    tag = "长期";
    source = "关于他是谁";
  } else if (has(compact, PREFERENCE)) {
    tag = "偏好";
    source = "他的口味";
  } else if (has(compact, EMOTION)) {
    tag = "情绪";
    source = "他那一刻的状态";
  }

  /*
   * ── ⑤ 长度门槛（按 tag 分档）──
   *
   * 这里踩过一个坑：第一版统一用「≥8 字」，结果把最该记的
   * 那几条全拦掉了：
   *
   *   「我不吃香菜」    5 字  ← 偏好，最该记
   *   「我叫阿野」      4 字  ← 身份，最该记
   *   「我在杭州上班」  6 字  ← 身份，最该记
   *
   * **最短的那几条往往最重要** —— 因为它们是事实，不是情绪。
   *
   * 而泛泛的短句（「我很好」「我也一样」）确实不该记，
   * 所以「短期」那一档保持 8 字。
   */
  const minLen = tag === "长期" || tag === "偏好" ? 4 : 8;
  if (s.length < minLen) return null;

  /* ── ⑥ 纯提问，而且问的不是关于他的事 ── */
  const isQuestion = /[？?]$/.test(s) || /^(你|您|为啥|为什么|怎么|多少|哪)/.test(s);
  if (isQuestion && tag === "短期") return null;

  /*
   * ── ⑥ 权重 ──
   *
   * **不直接用 forgetting.ts 里的 B 值** —— B 是衰减率，不是初始权重。
   *
   * 初始权重看的是「这条一开始有多重要」：
   *
   *   长期（他是谁）      0.85  —— 这种话一辈子就那么几次
   *   偏好（他的口味）    0.70  —— 知道了就不会忘
   *   情绪（那一刻的状态）0.55  —— 当下重要，但会过去
   *   短期（其他关于他）  0.45  —— 泛泛的，掉得快正常
   */
  const weight =
    tag === "长期" ? 0.85 : tag === "偏好" ? 0.7 : tag === "情绪" ? 0.55 : 0.45;

  return { text: s, tag, weight, source };
}

/**
 * 已经记过类似的了吗。
 *
 * **粗判**，不追求精确 —— 只防「同一句话连发三遍被记三次」。
 *
 * 判定：开头 10 个字相同，或者整句已经存在于最近 20 条里。
 */
export function isDuplicate(text: string, existing: Memory[]): boolean {
  const s = text.trim();
  if (!s) return false;
  const head = s.slice(0, 10);
  return existing
    .slice(0, 20)
    .some((m) => m.text === s || (head.length >= 8 && m.text.startsWith(head)));
}
